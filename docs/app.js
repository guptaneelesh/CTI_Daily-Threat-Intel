/* ============================================================
   CTI//DAILY-BRIEF — Client logic
   Loads docs/data.json (generated by scripts/aggregate.py)
   ============================================================ */

const STATE = {
  data: null,
  filters: {
    q: "",
    category: "",
    sector: "",
    priority: "",
    exploited: false,
    needsCve: false,
  },
};

const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => document.querySelectorAll(sel);

// ---------------- Boot ----------------
(async function init() {
  try {
    const res = await fetch("data.json", { cache: "no-store" });
    if (!res.ok) throw new Error("HTTP " + res.status);
    STATE.data = await res.json();
  } catch (err) {
    console.error("Failed to load data.json", err);
    $("#feed").innerHTML =
      '<p class="empty">Could not load data.json. Run <code>python scripts/aggregate.py</code> or wait for the next CI build.</p>';
    return;
  }

  renderHeader();
  renderStats();
  wireFilters();
  render();
})();

// ---------------- Render: header ----------------
function renderHeader() {
  const d = new Date(STATE.data.generated_at);
  $("#generated-at").textContent =
    "BUILD " + d.toISOString().replace("T", " ").slice(0, 16) + "Z";
  $("#lookback").textContent = "LOOKBACK " + STATE.data.lookback_hours + "H";
}

function renderStats() {
  const t = STATE.data.totals;
  $("#stat-all").textContent = t.all;
  $("#stat-critical").textContent = t.critical;
  $("#stat-high").textContent = t.high;
  $("#stat-medium").textContent = t.medium;
  $("#stat-exploited").textContent = t.actively_exploited;
  $("#stat-cves").textContent = t.with_cves;

  // Make stat tiles clickable shortcut filters
  $$(".stat").forEach((el) => {
    el.addEventListener("click", () => {
      resetFilters();
      const p = el.dataset.filterPriority;
      const ex = el.dataset.filterExploited;
      const cve = el.dataset.filterCve;
      if (p && p !== "all") { STATE.filters.priority = p; $("#f-priority").value = p; }
      if (ex)  { STATE.filters.exploited = true;  $("#f-exploited").checked = true; }
      if (cve) { STATE.filters.needsCve = true; }
      render();
    });
  });
}

// ---------------- Wire filters ----------------
function wireFilters() {
  $("#q").addEventListener("input", (e) => {
    STATE.filters.q = e.target.value.trim().toLowerCase();
    render();
  });
  $("#f-category").addEventListener("change", (e) => {
    STATE.filters.category = e.target.value;
    render();
  });
  $("#f-sector").addEventListener("change", (e) => {
    STATE.filters.sector = e.target.value;
    render();
  });
  $("#f-priority").addEventListener("change", (e) => {
    STATE.filters.priority = e.target.value;
    render();
  });
  $("#f-exploited").addEventListener("change", (e) => {
    STATE.filters.exploited = e.target.checked;
    render();
  });
  $("#reset").addEventListener("click", () => {
    resetFilters();
    render();
  });
}

function resetFilters() {
  STATE.filters = { q: "", category: "", sector: "", priority: "", exploited: false, needsCve: false };
  $("#q").value = "";
  $("#f-category").value = "";
  $("#f-sector").value = "";
  $("#f-priority").value = "";
  $("#f-exploited").checked = false;
}

// ---------------- Filter logic ----------------
function applyFilters(items) {
  const f = STATE.filters;
  return items.filter((it) => {
    if (f.category && it.category !== f.category) return false;
    if (f.priority && it.priority_label !== f.priority) return false;
    if (f.exploited && !it.actively_exploited) return false;
    if (f.needsCve && (!it.cves || it.cves.length === 0)) return false;
    if (f.sector && !(it.sectors || []).includes(f.sector)) return false;
    if (f.q) {
      const hay = (
        it.title +
        " " +
        it.summary +
        " " +
        it.source +
        " " +
        (it.cves || []).join(" ") +
        " " +
        (it.products || []).join(" ")
      ).toLowerCase();
      if (!hay.includes(f.q)) return false;
    }
    return true;
  });
}

// ---------------- Render ----------------
function render() {
  const items = applyFilters(STATE.data.items);
  renderHeadlines(items);
  renderFeed(items);
  $("#empty").classList.toggle("hidden", items.length > 0);
}

function renderHeadlines(items) {
  const ol = $("#headlines");
  ol.innerHTML = "";
  // Headlines = items from last 24h, sorted by priority score
  const cutoff = Date.now() / 1000 - 24 * 3600;
  const recent = items
    .filter((i) => i.published_ts >= cutoff)
    .slice(0, 15);
  if (recent.length === 0) {
    ol.innerHTML = '<li class="empty mono" style="grid-column: 1 / -1;">No items in last 24h matching filters.</li>';
    return;
  }
  recent.forEach((it, idx) => {
    const li = document.createElement("li");
    li.innerHTML = `
      <span class="hl-num">${String(idx + 1).padStart(2, "0")}</span>
      <span class="hl-pri ${it.priority_label}">${it.priority_label.toUpperCase()}</span>
      <a class="hl-title" href="${escapeAttr(it.url)}" target="_blank" rel="noopener">${escapeHTML(it.title)}</a>
      <span class="hl-source">${escapeHTML(it.source)}</span>
    `;
    // Clicking row body (not the link) scrolls to the card
    li.addEventListener("click", (e) => {
      if (e.target.tagName === "A") return;
      const card = document.querySelector(`[data-id="${it.id}"]`);
      if (card) {
        card.scrollIntoView({ behavior: "smooth", block: "center" });
        card.classList.add("flash");
        setTimeout(() => card.classList.remove("flash"), 1200);
      }
    });
    ol.appendChild(li);
  });
}

function renderFeed(items) {
  const feed = $("#feed");
  feed.innerHTML = "";
  const tpl = $("#card-tpl").content;

  items.forEach((it) => {
    const node = tpl.cloneNode(true);
    const article = node.querySelector(".card");
    article.dataset.id = it.id;
    article.classList.add("priority-" + it.priority_label);

    const pri = node.querySelector(".pill.priority");
    pri.textContent = it.priority_label.toUpperCase() + " · " + it.priority_score;
    pri.classList.add(it.priority_label);

    node.querySelector(".pill.category").textContent = it.category.toUpperCase();

    const ex = node.querySelector(".pill.exploited");
    if (it.actively_exploited) ex.classList.remove("hidden");

    const cvss = node.querySelector(".pill.cvss");
    if (it.cvss != null) {
      cvss.textContent = "CVSS " + it.cvss.toFixed(1);
      cvss.classList.remove("hidden");
    }

    node.querySelector(".when").textContent = relTime(it.published_ts);

    node.querySelector(".card-title").textContent = it.title;
    node.querySelector(".card-summary").textContent =
      it.summary || "(no summary provided by source)";

    fillTags(node, ".meta-row.cves", it.cves, "cve");
    fillTags(node, ".meta-row.products", it.products);
    fillTags(node, ".meta-row.sectors", it.sectors);
    fillTags(node, ".meta-row.regions", it.regions);
    fillTags(node, ".meta-row.sources", [it.source]);

    const link = node.querySelector(".card-link");
    link.href = it.url;
    link.textContent = "read on " + it.source + " →";

    const relToggle = node.querySelector(".related-toggle");
    const relBox = node.querySelector(".related");
    if ((it.related_sources || []).length > 0) {
      relToggle.classList.remove("hidden");
      relToggle.querySelector(".related-count").textContent = it.related_sources.length;
      relBox.innerHTML = it.related_sources
        .map(
          (r) =>
            `<a href="${escapeAttr(r.url)}" target="_blank" rel="noopener">
               <span class="rs-source">${escapeHTML(r.source)}</span>${escapeHTML(r.title)}
             </a>`
        )
        .join("");
      relToggle.addEventListener("click", () => {
        relBox.classList.toggle("hidden");
      });
    }
    feed.appendChild(node);
  });
}

function fillTags(parent, selector, values, extraClass = "") {
  const row = parent.querySelector(selector);
  if (!values || values.length === 0) return;
  row.classList.remove("hidden");
  const valEl = row.querySelector(".meta-val");
  valEl.innerHTML = values
    .map((v) => `<span class="tag ${extraClass}">${escapeHTML(v)}</span>`)
    .join("");
}

// ---------------- Utils ----------------
function relTime(ts) {
  const diff = (Date.now() / 1000 - ts);
  if (diff < 60) return Math.floor(diff) + "s ago";
  if (diff < 3600) return Math.floor(diff / 60) + "m ago";
  if (diff < 86400) return Math.floor(diff / 3600) + "h ago";
  return Math.floor(diff / 86400) + "d ago";
}

function escapeHTML(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
function escapeAttr(s) { return escapeHTML(s); }

// flash effect for headline → card scroll
const styleFlash = document.createElement("style");
styleFlash.textContent = `
  .card.flash { animation: flash 1.2s ease; }
  @keyframes flash {
    0%   { box-shadow: 0 0 0 0 rgba(0,255,156,0.6); }
    40%  { box-shadow: 0 0 0 6px rgba(0,255,156,0.25); }
    100% { box-shadow: 0 0 0 0 rgba(0,255,156,0); }
  }
`;
document.head.appendChild(styleFlash);
